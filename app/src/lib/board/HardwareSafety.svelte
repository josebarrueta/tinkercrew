<aside aria-label="Hardware safety">
  <h3>Power off before changing wiring</h3>
  <ul>
    <li>
      UNO Q maker GPIO uses <strong>3.3 V logic</strong>. Never apply 5 V to
      analog inputs.
    </li>
    <li>Ordinary LEDs need suitable current-limiting resistors.</li>
    <li>
      Never drive motors or high-current loads directly from GPIO; they need an
      appropriate driver and power supply.
    </li>
    <li>
      The RexQualis breadboard power module is excluded from beginner Missions
      until separately validated.
    </li>
    <li>
      Disconnect power before moving wires or reconnecting components. Ask a
      grown-up if unsure.
    </li>
  </ul>
</aside>

